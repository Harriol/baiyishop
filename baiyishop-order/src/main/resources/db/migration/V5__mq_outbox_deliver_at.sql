-- ============================================================================
-- 订单侧本地消息表增加 deliver_at（延时投递）
--
-- 背景：订单的两条消息都是**延时**消息 —— 15 分钟未支付自动取消（REQ-704）、
-- 发货后 7 天自动确认收货（REQ-707）。RocketMQ 的固定延时等级（1s/5s/…/2h）
-- 覆盖不了「15 分钟」「7 天」，故记录绝对投递时间，投递任务用
-- RocketMQ 5.x 的定时消息（setDeliverTimeMs）按点发送。
--
-- 兜底：定时任务会扫描「已超时仍待付款」「发货超 7 天仍待收货」的订单补处理，
-- 因此即使定时消息不可用（提前投递或丢失），业务结果依然正确。
-- ============================================================================

ALTER TABLE mq_outbox
    ADD COLUMN deliver_at DATETIME(3) DEFAULT NULL COMMENT '计划投递时间（延时消息用，NULL 表示立即投递）' AFTER next_retry_at;
